# ==========================================================================================
#  RAM Doctor - the ONE string table (src/lib/Strings.ps1)
#
#  Every sentence the user can read lives here, in two tables: 'ar' (Arabic, the original
#  language of the product) and 'en' (English). Nothing else in the code base carries a
#  user-facing literal, so a translator (or a reviewer) only ever opens this file.
#
#    Get-Text 'key'                    -> the text in the current language
#    Get-Text 'key' $a $b              -> templates use .NET composite format: {0} {1} ... (arguments are
#                                         formatted with the invariant culture; a template that is looked up
#                                         WITHOUT arguments is returned as it is, so braces need no escaping there)
#    Get-Text 'key' -Lang en           -> force a language for this one lookup
#    Set-UiLang 'en' | 'ar' | ''       -> choose the language ('' = detect)
#    Get-UiLang                        -> the language in use
#
#  Language rule: Arabic when the Windows UI language is Arabic, English otherwise; every script that
#  shows text also accepts  -Lang ar|en  to override it.  Nothing is saved to disk.
#
#  Conventions
#    * Keys are  area.topic[.part]:  sig.* scan signals, obs.* observations, verdict.*, tag.*, anom.*,
#      trust.* / level.* labels, rpt.* the HTML report, gui.* the window, share.* the share client,
#      sum.* the short chat summary.
#    * "\n" inside a template is a line break (applied to the template, never to the arguments).
#    * A few rpt.* templates contain trusted inline markup (<b>, <br>, <span>): their arguments are
#      built by the report code (already escaped) and the template itself never carries user data.
#    * Single-quoted strings: an apostrophe would have to be doubled, so English text avoids them.
#    * Keep both tables in the same order. tests\Strings.Tests.ps1 fails on a missing key, a different
#      placeholder set, Arabic text inside the English table, or a key that no source file uses.
#
#  Keep this file UTF-8 WITH BOM (Arabic text).
# ==========================================================================================

function Resolve-UiLang {
    # 'ar' / 'en' as given, otherwise the Windows UI language (Arabic -> 'ar', everything else -> 'en')
    param([string]$Lang = '')
    if ($Lang -match '^(?i)\s*(ar|en)(?:[-_]\w+)?\s*$') { return $Matches[1].ToLowerInvariant() }   # 'ar', 'en', 'ar-SA', 'en-US'
    try { if ((Get-UICulture).TwoLetterISOLanguageName -eq 'ar') { return 'ar' } } catch { }
    return 'en'
}

function Set-UiLang {
    param([string]$Lang = '')
    $script:UiLang = Resolve-UiLang $Lang
}

function Get-UiLang {
    if (-not $script:UiLang) { $script:UiLang = Resolve-UiLang }
    return $script:UiLang
}

function Test-TextKey {
    param([Parameter(Mandatory)][string]$Key, [string]$Lang = '')
    $l = if ($Lang) { Resolve-UiLang $Lang } else { Get-UiLang }
    return $script:RdText[$l].ContainsKey($Key)
}

function Get-Text {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory, Position = 0)][string]$Key,
        [Parameter(ValueFromRemainingArguments = $true)][object[]]$FormatArgs,
        [string]$Lang = ''
    )
    $l = if ($Lang) { Resolve-UiLang $Lang } else { Get-UiLang }
    $t = $script:RdText[$l]
    if (-not $t.ContainsKey($Key)) {
        # never a blank: a missing key is visible (and caught by tests\Strings.Tests.ps1)
        if ($script:RdText['ar'].ContainsKey($Key) -and $l -ne 'ar') { $t = $script:RdText['ar'] } else { return "[[$Key]]" }
    }
    $s = ([string]$t[$Key]).Replace('\n', "`n")
    if ($null -eq $FormatArgs -or $FormatArgs.Count -eq 0) { return $s }
    return [string]::Format([System.Globalization.CultureInfo]::InvariantCulture, $s, [object[]]$FormatArgs)
}

